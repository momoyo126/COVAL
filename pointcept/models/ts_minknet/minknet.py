import torch
import torch.nn as nn
import torchsparse.nn as spnn


def pad_to_multiple_of_4(feat):
    """
    Pads the feature tensor's channel dimension to the nearest multiple of 4.

    Args:
        feat (torch.Tensor): Input tensor of shape (N, C).

    Returns:
        torch.Tensor: Output tensor of shape (N, C_padded), where C_padded is the nearest multiple of 4.
    """
    N, C = feat.shape
    # Calculate the nearest multiple of 4 greater than or equal to C
    C_padded = (C + 3) // 4 * 4
    # Create a new tensor with the padded shape and initialize with zeros
    padded_feat = torch.zeros((N, C_padded), device=feat.device, dtype=feat.dtype)
    # Copy the original features into the padded tensor
    padded_feat[:, :C] = feat
    return padded_feat


class BasicConvolutionBlock(nn.Module):

    def __init__(self, inc, outc, ks=3, stride=1, dilation=1):
        super().__init__()
        self.net = nn.Sequential(
            spnn.Conv3d(inc,
                        outc,
                        kernel_size=ks,
                        dilation=dilation,
                        stride=stride),
            spnn.BatchNorm(outc),
            spnn.ReLU(True),
        )

    def forward(self, x):
        out = self.net(x)
        return out


class BasicDeconvolutionBlock(nn.Module):

    def __init__(self, inc, outc, ks=3, stride=1):
        super().__init__()
        self.net = nn.Sequential(
            spnn.Conv3d(inc,
                        outc,
                        kernel_size=ks,
                        stride=stride,
                        transposed=True),
            spnn.BatchNorm(outc),
            spnn.ReLU(True),
        )

    def forward(self, x):
        return self.net(x)


class ResidualBlock(nn.Module):

    def __init__(self, inc, outc, ks=3, stride=1, dilation=1):
        super().__init__()
        self.net = nn.Sequential(
            spnn.Conv3d(inc,
                        outc,
                        kernel_size=ks,
                        dilation=dilation,
                        stride=stride),
            spnn.BatchNorm(outc),
            spnn.ReLU(True),
            spnn.Conv3d(outc, outc, kernel_size=ks, dilation=dilation,
                        stride=1),
            spnn.BatchNorm(outc),
        )

        if inc == outc and stride == 1:
            self.downsample = nn.Sequential()
        else:
            self.downsample = nn.Sequential(
                spnn.Conv3d(inc, outc, kernel_size=1, dilation=1,
                            stride=stride),
                spnn.BatchNorm(outc),
            )

        self.relu = spnn.ReLU(True)

    def forward(self, x):
        out = self.relu(self.net(x) + self.downsample(x))
        return out
